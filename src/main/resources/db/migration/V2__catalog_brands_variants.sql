-- ─────────────────────────────────────────────────────────────────────────────
-- V2__catalog_brands_variants.sql — catalogue brand + variant support
--
-- Extends V1 without changing existing product/category semantics:
--   • brands table + products.brand_id FK (optional, like category_id)
--   • product_variants table for sellable options (size/colour/etc.) with a SKU
--   • the existing catalogue filters stay active-only; variants are active-only too
--
-- Money/audit/naming conventions mirror V1.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE brands (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    slug            VARCHAR(160) NOT NULL,
    description     VARCHAR(1000),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uk_brands_slug UNIQUE (slug)
);
CREATE INDEX idx_brands_active ON brands (active);

ALTER TABLE products
    ADD COLUMN brand_id BIGINT REFERENCES brands (id) ON DELETE SET NULL;
CREATE INDEX idx_products_brand ON products (brand_id);

CREATE TABLE product_variants (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    sku            VARCHAR(64)  NOT NULL,
    name           VARCHAR(150) NOT NULL,
    options        VARCHAR(500),
    price          NUMERIC(12,2),
    currency       VARCHAR(3),
    stock_quantity INTEGER      NOT NULL DEFAULT 0,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version        BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uk_product_variants_sku UNIQUE (sku)
);
CREATE INDEX idx_product_variants_product ON product_variants (product_id);
CREATE INDEX idx_product_variants_active   ON product_variants (active);
