-- V6__reviews.sql — product reviews. One review per (user, product); the service
-- rejects the second insert with a 409 rather than relying on the constraint.

CREATE TABLE reviews (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating      INTEGER       NOT NULL,
    title       VARCHAR(150),
    body        VARCHAR(2000),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_reviews_product_user UNIQUE (product_id, user_id),
    CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_reviews_product ON reviews (product_id);
CREATE INDEX idx_reviews_user ON reviews (user_id);
