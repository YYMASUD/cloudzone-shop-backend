-- V4__coupons.sql — discount codes. `times_redeemed` is incremented transactionally
-- inside checkout; CHECK guards reject nonsensical percentages/values up front.

CREATE TABLE coupons (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(50)   NOT NULL,
    description      VARCHAR(255),
    discount_type    VARCHAR(20)   NOT NULL,
    discount_value   NUMERIC(12,2) NOT NULL,
    min_order_total  NUMERIC(12,2),
    max_redemptions  INTEGER,
    times_redeemed   INTEGER       NOT NULL DEFAULT 0,
    expires_at       TIMESTAMPTZ,
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_coupons_code UNIQUE (code),
    CONSTRAINT chk_coupons_discount_type CHECK (discount_type IN ('PERCENT', 'FIXED')),
    CONSTRAINT chk_coupons_discount_value CHECK (discount_value >= 0)
);

CREATE INDEX idx_coupons_active ON coupons (active);
CREATE INDEX idx_coupons_expires_at ON coupons (expires_at);
