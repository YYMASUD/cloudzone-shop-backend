-- ─────────────────────────────────────────────────────────────────────────────
-- V1__init.sql  —  Initial e-commerce schema
--
-- Design notes
--   • Money           -> NUMERIC(12,2) + ISO-4217 currency column (never float)
--   • Audit           -> created_at / updated_at (timestamptz) on every table
--   • Optimistic lock -> version BIGINT on every table (JPA @Version)
--   • Snapshots       -> cart/order lines copy unit_price & product name/sku so
--                        later catalog changes never corrupt history
--   • Naming          -> snake_case plural tables matching Hibernate's default
--                        PhysicalNamingStrategy (ddl-auto=validate is on)
-- ─────────────────────────────────────────────────────────────────────────────

-- ── USERS ────────────────────────────────────────────────────────────────────
CREATE TABLE users (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(100),
    first_name      VARCHAR(100),
    last_name       VARCHAR(100),
    phone           VARCHAR(30),
    role            VARCHAR(20)  NOT NULL,
    auth_provider   VARCHAR(20)  NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT chk_users_role          CHECK (role IN ('CUSTOMER','ADMIN')),
    CONSTRAINT chk_users_auth_provider CHECK (auth_provider IN ('LOCAL','GOOGLE','APPLE'))
);

CREATE TABLE addresses (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label           VARCHAR(50),
    recipient_name  VARCHAR(150) NOT NULL,
    line1           VARCHAR(255) NOT NULL,
    line2           VARCHAR(255),
    city            VARCHAR(100) NOT NULL,
    state           VARCHAR(100),
    postal_code     VARCHAR(20),
    country         VARCHAR(2)   NOT NULL,
    is_default      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX idx_addresses_user ON addresses (user_id);

-- ── CATALOG ──────────────────────────────────────────────────────────────────
CREATE TABLE categories (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    slug            VARCHAR(160) NOT NULL,
    description     VARCHAR(1000),
    parent_id       BIGINT       REFERENCES categories (id) ON DELETE SET NULL,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uk_categories_slug UNIQUE (slug)
);
CREATE INDEX idx_categories_parent ON categories (parent_id);

CREATE TABLE products (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(64)   NOT NULL,
    name             VARCHAR(255)  NOT NULL,
    slug             VARCHAR(280)  NOT NULL,
    description      TEXT,
    price            NUMERIC(12,2) NOT NULL,
    compare_at_price NUMERIC(12,2),
    currency         VARCHAR(3)    NOT NULL DEFAULT 'USD',
    stock_quantity   INTEGER       NOT NULL DEFAULT 0,
    category_id      BIGINT        REFERENCES categories (id) ON DELETE SET NULL,
    image_key        VARCHAR(512),
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version          BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT uk_products_sku  UNIQUE (sku),
    CONSTRAINT uk_products_slug UNIQUE (slug),
    CONSTRAINT chk_products_price_nonneg CHECK (price >= 0),
    CONSTRAINT chk_products_stock_nonneg CHECK (stock_quantity >= 0)
);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_active   ON products (active);
CREATE INDEX idx_products_name     ON products (name);

-- ── CART ─────────────────────────────────────────────────────────────────────
CREATE TABLE carts (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version         BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uk_carts_user UNIQUE (user_id)
);

CREATE TABLE cart_items (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id         BIGINT        NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id      BIGINT        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    quantity        INTEGER       NOT NULL,
    unit_price      NUMERIC(12,2) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version         BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT uk_cart_items_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT chk_cart_items_qty   CHECK (quantity > 0),
    CONSTRAINT chk_cart_items_price CHECK (unit_price >= 0)
);
CREATE INDEX idx_cart_items_cart ON cart_items (cart_id);

-- ── ORDERS ───────────────────────────────────────────────────────────────────
CREATE TABLE orders (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number         VARCHAR(32)   NOT NULL,
    user_id              BIGINT        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status               VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    subtotal             NUMERIC(12,2) NOT NULL,
    shipping_cost        NUMERIC(12,2) NOT NULL DEFAULT 0,
    tax                  NUMERIC(12,2) NOT NULL DEFAULT 0,
    total                NUMERIC(12,2) NOT NULL,
    currency             VARCHAR(3)    NOT NULL DEFAULT 'USD',
    shipping_address_id  BIGINT        REFERENCES addresses (id) ON DELETE SET NULL,
    billing_address_id   BIGINT        REFERENCES addresses (id) ON DELETE SET NULL,
    notes                VARCHAR(1000),
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version              BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT uk_orders_number UNIQUE (order_number),
    CONSTRAINT chk_orders_status CHECK (status IN
        ('PENDING','PAID','PROCESSING','SHIPPED','DELIVERED','CANCELLED','REFUNDED'))
);
CREATE INDEX idx_orders_user   ON orders (user_id);
CREATE INDEX idx_orders_status ON orders (status);

CREATE TABLE order_items (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id      BIGINT        NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    product_name    VARCHAR(255)  NOT NULL,
    product_sku     VARCHAR(64)   NOT NULL,
    quantity        INTEGER       NOT NULL,
    unit_price      NUMERIC(12,2) NOT NULL,
    line_total      NUMERIC(12,2) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version         BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT chk_order_items_qty   CHECK (quantity > 0),
    CONSTRAINT chk_order_items_price CHECK (unit_price >= 0)
);
CREATE INDEX idx_order_items_order   ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);

-- ── PAYMENTS ─────────────────────────────────────────────────────────────────
CREATE TABLE payments (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method             VARCHAR(20)   NOT NULL,
    status             VARCHAR(20)   NOT NULL DEFAULT 'INITIATED',
    amount             NUMERIC(12,2) NOT NULL,
    currency           VARCHAR(3)    NOT NULL,
    gateway_reference  VARCHAR(255),
    gateway_payload    TEXT,
    failure_reason     VARCHAR(500),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version            BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT chk_payments_method CHECK (method IN
        ('STRIPE','RAZORPAY','PAYPAL','SSLCOMMERZ')),
    CONSTRAINT chk_payments_status CHECK (status IN
        ('INITIATED','PENDING','SUCCEEDED','FAILED','CANCELLED','REFUNDED'))
);
CREATE INDEX idx_payments_order   ON payments (order_id);
CREATE INDEX idx_payments_gateway ON payments (gateway_reference);
CREATE INDEX idx_payments_status  ON payments (status);

-- ── IDEMPOTENCY ──────────────────────────────────────────────────────────────
CREATE TABLE idempotency_records (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key      VARCHAR(255) NOT NULL,
    request_fingerprint  VARCHAR(512),
    response_status      INTEGER,
    response_body        TEXT,
    expires_at           TIMESTAMPTZ  NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version              BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uk_idempotency_key UNIQUE (idempotency_key)
);
CREATE INDEX idx_idempotency_expires ON idempotency_records (expires_at);
