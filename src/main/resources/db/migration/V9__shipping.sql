-- V9__shipping.sql — shipping method catalog (admin-managed flat rates) plus the
-- shipment record created once an order is dispatched.

CREATE TABLE shipping_methods (
    id               BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(50)    NOT NULL,
    name             VARCHAR(150)   NOT NULL,
    description      VARCHAR(255),
    flat_rate        NUMERIC(12,2)  NOT NULL,
    estimated_days   INTEGER,
    active           BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version          BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_shipping_methods_code UNIQUE (code),
    CONSTRAINT chk_shipping_methods_rate CHECK (flat_rate >= 0)
);

CREATE INDEX idx_shipping_methods_active ON shipping_methods (active);

CREATE TABLE shipments (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method_id        BIGINT        REFERENCES shipping_methods (id) ON DELETE SET NULL,
    tracking_number  VARCHAR(100),
    carrier          VARCHAR(100),
    shipped_at       TIMESTAMPTZ,
    delivered_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_shipments_order UNIQUE (order_id)
);

CREATE INDEX idx_shipments_order ON shipments (order_id);
