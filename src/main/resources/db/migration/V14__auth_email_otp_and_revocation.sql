-- ─────────────────────────────────────────────────────────────────────────────
-- V14__auth_email_otp_and_revocation.sql — email-OTP verification + token revocation
--
-- Two independent auth gaps share one migration because both are small lookup tables
-- keyed by user / token id:
--
--   email_verification_tokens  single-use 6-digit OTPs that flip users.email_verified.
--                              The code is stored SHA-256-hashed (never in clear) so a
--                              read of the table can't mint a verification. expires_at
--                              bounds the guess window; used_at enforces single-use.
--
--   revoked_tokens             the jti denylist consulted by the refresh exchange on
--                              every rotation. A row here means "this refresh token id
--                              was logged out / revoked" — access tokens are not revoked
--                              (they're short-lived by design).
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE email_verification_tokens (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_hash    VARCHAR(64)  NOT NULL,                -- SHA-256 hex of the 6-digit code
    expires_at   TIMESTAMPTZ  NOT NULL,
    used_at      TIMESTAMPTZ,                          -- null until the code is confirmed
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version      BIGINT       NOT NULL DEFAULT 0
);

-- Lookups always filter by user + unused; a plain composite index serves them (H2 —
-- the test database — doesn't support partial-index WHERE clauses).
CREATE INDEX idx_evt_user_active ON email_verification_tokens (user_id, used_at);

CREATE TABLE revoked_tokens (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti         VARCHAR(64)  NOT NULL,                 -- the refresh token's jti claim
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at  TIMESTAMPTZ  NOT NULL,                 -- lets a sweep drop dead entries
    revoked_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_revoked_tokens_jti UNIQUE (jti)
);

-- The refresh exchange checks membership by jti on every call.
CREATE INDEX idx_revoked_tokens_jti ON revoked_tokens (jti);
