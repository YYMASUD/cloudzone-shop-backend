-- V8__media.sql — uploaded media assets (files stored in MinIO object storage;
-- this table is the DB index so admin endpoints can browse and reference them).

CREATE TABLE media_assets (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    file_name     VARCHAR(255)  NOT NULL,
    object_key    VARCHAR(512)  NOT NULL,
    content_type  VARCHAR(100),
    size_bytes    BIGINT,
    alt_text      VARCHAR(255),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_media_assets_object_key UNIQUE (object_key)
);

CREATE INDEX idx_media_assets_owner ON media_assets (owner_user_id);
